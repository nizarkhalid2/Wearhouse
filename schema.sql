create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  email text not null default '',
  role text not null default 'delivery_guy' check (role in ('admin','delivery_guy')),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

-- Migration support for earlier versions of this project.
alter table public.profiles add column if not exists email text not null default '';
alter table public.profiles add column if not exists active boolean not null default true;

create table if not exists public.inventory_units (
  id uuid primary key default gen_random_uuid(),
  product_id uuid not null references public.products(id) on delete cascade,
  serial_number text not null unique,
  status text not null default 'available' check (status in ('available','reserved','out_for_delivery','delivered')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.delivery_requests (
  id uuid primary key default gen_random_uuid(),
  delivery_guy_id uuid not null references auth.users(id) on delete restrict,
  product_id uuid not null references public.products(id) on delete restrict,
  unit_id uuid not null references public.inventory_units(id) on delete restrict,
  destination text not null,
  recipient text not null default '',
  delivery_date date not null,
  notes text not null default '',
  status text not null default 'pending_admin_approval' check (status in ('pending_admin_approval','approved_for_delivery','delivery_note_submitted','completed','rejected')),
  delivery_note_url text not null default '',
  delivery_note_number text not null default '',
  driver_notes text not null default '',
  rejection_reason text not null default '',
  created_at timestamptz not null default now(),
  approved_at timestamptz,
  delivered_at timestamptz,
  completed_at timestamptz,
  approved_by uuid references auth.users(id),
  completed_by uuid references auth.users(id)
);

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  recipient_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  body text not null default '',
  type text not null default 'delivery',
  reference_id uuid,
  read_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists inventory_units_product_idx on public.inventory_units(product_id);
create index if not exists inventory_units_status_idx on public.inventory_units(status);
create index if not exists delivery_requests_driver_idx on public.delivery_requests(delivery_guy_id);
create index if not exists delivery_requests_status_idx on public.delivery_requests(status);
create index if not exists notifications_recipient_idx on public.notifications(recipient_id, created_at desc);

-- Only one active delivery workflow may own a serial at a time.
create unique index if not exists delivery_requests_one_active_unit
on public.delivery_requests(unit_id)
where status in ('pending_admin_approval','approved_for_delivery','delivery_note_submitted');

