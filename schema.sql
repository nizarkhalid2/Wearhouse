-- Products: public catalog; admin writes.
drop policy if exists "public can view products" on public.products;
create policy "public can view products" on public.products for select using (true);

drop policy if exists "admins can insert products" on public.products;
create policy "admins can insert products" on public.products for insert to authenticated with check (public.is_admin());

drop policy if exists "admins can update products" on public.products;
create policy "admins can update products" on public.products for update to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "admins can delete products" on public.products;
create policy "admins can delete products" on public.products for delete to authenticated using (public.is_admin());

-- Admin membership: users only see their own row.
drop policy if exists "admins can read own admin row" on public.admin_users;
create policy "admins can read own admin row" on public.admin_users for select to authenticated using (user_id = auth.uid());

-- Activity remains readable with the public catalog.
drop policy if exists "public can view activity" on public.activity;
create policy "public can view activity" on public.activity for select using (true);

drop policy if exists "admins can insert activity" on public.activity;
create policy "admins can insert activity" on public.activity for insert to authenticated with check (public.is_admin());

-- Profiles: own profile or all profiles for admin; admin can manage status.
drop policy if exists "users can read own profile" on public.profiles;
drop policy if exists "staff profiles read" on public.profiles;
create policy "staff profiles read" on public.profiles for select to authenticated using (id = auth.uid() or public.is_admin());

drop policy if exists "admins can update profiles" on public.profiles;
create policy "admins can update profiles" on public.profiles for update to authenticated using (public.is_admin()) with check (public.is_admin());

-- Serial numbers are private to warehouse staff.
drop policy if exists "public can read units" on public.inventory_units;
drop policy if exists "staff can read units" on public.inventory_units;
create policy "staff can read units" on public.inventory_units for select to authenticated using (public.is_admin() or public.is_delivery());

drop policy if exists "admins can manage units" on public.inventory_units;
create policy "admins can manage units" on public.inventory_units for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- Delivery requests: driver sees/creates own; admin sees all and controls state.
drop policy if exists "delivery can read own requests" on public.delivery_requests;
create policy "delivery can read own requests" on public.delivery_requests for select to authenticated using (delivery_guy_id = auth.uid() or public.is_admin());

drop policy if exists "delivery can create requests" on public.delivery_requests;
create policy "delivery can create requests" on public.delivery_requests for insert to authenticated with check (
  delivery_guy_id = auth.uid()
  and public.is_delivery()
  and exists (
    select 1 from public.inventory_units u
    where u.id = delivery_requests.unit_id and u.product_id = delivery_requests.product_id and u.status = 'available'
  )
);

-- Drivers submit notes only through submit_delivery_note() RPC.
drop policy if exists "delivery can submit notes" on public.delivery_requests;

drop policy if exists "admins can update deliveries" on public.delivery_requests;
create policy "admins can update deliveries" on public.delivery_requests for update to authenticated using (public.is_admin()) with check (public.is_admin());

-- Notifications: only the recipient can read/mark them.
drop policy if exists "users can read own notifications" on public.notifications;
create policy "users can read own notifications" on public.notifications for select to authenticated using (recipient_id = auth.uid());

drop policy if exists "users can mark own notifications" on public.notifications;
create policy "users can mark own notifications" on public.notifications for update to authenticated using (recipient_id = auth.uid()) with check (recipient_id = auth.uid());

