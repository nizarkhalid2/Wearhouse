create or replace function public.approve_delivery_request(request_id uuid)
returns public.delivery_requests
language plpgsql
security definer
set search_path = public
as $$
declare r public.delivery_requests;
begin
  if not public.is_admin() then raise exception 'Admin access required'; end if;

  select * into r from public.delivery_requests where id = request_id for update;
  if r.id is null then raise exception 'Delivery request not found'; end if;
  if r.status <> 'pending_admin_approval' then raise exception 'Request is not awaiting approval'; end if;

  update public.inventory_units
  set status = 'reserved'
  where id = r.unit_id and product_id = r.product_id and status = 'available';
  if not found then raise exception 'This serial number is no longer available'; end if;

  update public.delivery_requests
  set status = 'approved_for_delivery', approved_at = now(), approved_by = auth.uid(), rejection_reason = ''
  where id = request_id
  returning * into r;

  insert into public.notifications(recipient_id, title, body, type, reference_id)
  values (
    r.delivery_guy_id,
    'Delivery approved',
    'Your delivery request for serial ' || (select serial_number from public.inventory_units where id = r.unit_id) || ' was approved.',
    'delivery',
    r.id
  );

  return r;
end;
$$;

create or replace function public.reject_delivery_request(request_id uuid, rejection_reason text default '')
returns public.delivery_requests
language plpgsql
security definer
set search_path = public
as $$
declare r public.delivery_requests;
begin
  if not public.is_admin() then raise exception 'Admin access required'; end if;

  select * into r from public.delivery_requests where id = request_id for update;
  if r.id is null then raise exception 'Delivery request not found'; end if;
  if r.status in ('completed','rejected') then raise exception 'This request is already closed'; end if;

  if r.status in ('approved_for_delivery','delivery_note_submitted') then
    update public.inventory_units
    set status = 'available'
    where id = r.unit_id and status in ('reserved','out_for_delivery');
  end if;

  update public.delivery_requests
  set status = 'rejected', rejection_reason = coalesce(rejection_reason, '')
  where id = request_id
  returning * into r;

  insert into public.notifications(recipient_id, title, body, type, reference_id)
  values (
    r.delivery_guy_id,
    'Delivery rejected',
    'Your delivery request was rejected.' || case when coalesce(rejection_reason,'') <> '' then ' Reason: ' || rejection_reason else '' end,
    'delivery',
    r.id
  );

  return r;
end;
$$;

create or replace function public.submit_delivery_note(
  request_id uuid,
  note_path text,
  note_number text default '',
  note_text text default ''
)
returns public.delivery_requests
language plpgsql
security definer
set search_path = public
as $$
declare r public.delivery_requests;
begin
  if not public.is_delivery() then raise exception 'Delivery access required'; end if;
  if coalesce(note_path, '') = '' then raise exception 'Delivery note file is required'; end if;

  select * into r
  from public.delivery_requests
  where id = request_id and delivery_guy_id = auth.uid()
  for update;

  if r.id is null then raise exception 'Delivery request not found'; end if;
  if r.status <> 'approved_for_delivery' then raise exception 'This delivery is not ready for a note'; end if;

  update public.inventory_units
  set status = 'out_for_delivery'
  where id = r.unit_id and status = 'reserved';
  if not found then raise exception 'Reserved inventory unit not found'; end if;

  update public.delivery_requests
  set status = 'delivery_note_submitted',
      delivery_note_url = note_path,
      delivery_note_number = coalesce(note_number, ''),
      driver_notes = coalesce(note_text, ''),
      delivered_at = now()
  where id = request_id
  returning * into r;

  return r;
end;
$$;

create or replace function public.complete_delivery_request(request_id uuid)
returns public.delivery_requests
language plpgsql
security definer
set search_path = public
as $$
declare r public.delivery_requests;
begin
  if not public.is_admin() then raise exception 'Admin access required'; end if;

  select * into r from public.delivery_requests where id = request_id for update;
  if r.id is null then raise exception 'Delivery request not found'; end if;
  if r.status <> 'delivery_note_submitted' then raise exception 'Delivery note must be submitted first'; end if;

  update public.inventory_units
  set status = 'delivered'
  where id = r.unit_id and status in ('reserved','out_for_delivery');
  if not found then raise exception 'Inventory unit is not reserved/out for delivery'; end if;

  update public.products
  set quantity = greatest(0, quantity - 1)
  where id = r.product_id;

  update public.delivery_requests
  set status = 'completed', completed_at = now(), completed_by = auth.uid()
  where id = request_id
  returning * into r;

  insert into public.notifications(recipient_id, title, body, type, reference_id)
  values (
    r.delivery_guy_id,
    'Delivery completed',
    'Delivery for serial ' || (select serial_number from public.inventory_units where id = r.unit_id) || ' was completed successfully.',
    'delivery',
    r.id
  );

  return r;
end;
$$;

revoke all on function public.approve_delivery_request(uuid) from public;
revoke all on function public.reject_delivery_request(uuid,text) from public;
revoke all on function public.submit_delivery_note(uuid,text,text,text) from public;
