-- Keep updated_at current.
create or replace function public.touch_product()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists products_touch on public.products;
create trigger products_touch before update on public.products
for each row execute function public.touch_product();

-- Automatic audit trail. This means the browser does not need to be trusted to write logs.
create or replace function public.log_product_activity()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    insert into public.activity(product_id, action, product_name, actor_email)
    values (new.id, 'created', new.name, coalesce(auth.jwt()->>'email',''));
    return new;
  elsif tg_op = 'UPDATE' then
    insert into public.activity(product_id, action, product_name, actor_email)
    values (new.id, 'updated', new.name, coalesce(auth.jwt()->>'email',''));
    return new;
  elsif tg_op = 'DELETE' then
    insert into public.activity(product_id, action, product_name, actor_email)
    values (old.id, 'deleted', old.name, coalesce(auth.jwt()->>'email',''));
    return old;
  end if;
  return null;
end;
$$;

drop trigger if exists products_activity on public.products;
create trigger products_activity after insert or update or delete on public.products
for each row execute function public.log_product_activity();

