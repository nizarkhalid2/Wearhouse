create or replace function public.approve_delivery_request(request_id uuid)
returns public.delivery_requests
language plpgsql
security definer set search_path=public
as $$
declare r public.delivery_requests;
begin
  if not public.is_admin() then raise exception 'Admin access required'; end if;
  select * into r from public.delivery_requests where id=request_id for update;
  if r.id is null then raise exception 'Delivery request not found'; end if;
  if r.status <> 'pending_admin_approval' then raise exception 'Request is not awaiting approval'; end if;

  update public.inventory_units
  set status='reserved', updated_at=now()
  where id=r.unit_id and status='available';
  if not found then raise exception 'This serial number is no longer available'; end if;

  update public.delivery_requests
  set status='approved_for_delivery', approved_at=now(), approved_by=auth.uid()
  where id=request_id returning * into r;

  insert into public.notifications(recipient_id,title,body,type,reference_id)
  values(r.delivery_guy_id,'Delivery approved',
         'Your delivery request for serial ' || (select serial_number from public.inventory_units where id=r.unit_id) || ' was approved.',
         'delivery',r.id);

  return r;
end;
$$;

create or replace function public.reject_delivery_request(request_id uuid, rejection_reason text default '')
returns public.delivery_requests
language plpgsql
security definer set search_path=public
as $$
declare r public.delivery_requests;
begin
  if not public.is_admin() then raise exception 'Admin access required'; end if;
  select * into r from public.delivery_requests where id=request_id for update;
  if r.id is null then raise exception 'Delivery request not found'; end if;

  if r.status='approved_for_delivery' or r.status='pending_admin_approval' or r.status='delivery_note_submitted' then
    update public.inventory_units set status='available', updated_at=now()
    where id=r.unit_id and status in ('reserved','out_for_delivery');
  end if;

  update public.delivery_requests
  set status='rejected', rejection_reason=coalesce(rejection_reason,'')
  where id=request_id returning * into r;

  insert into public.notifications(recipient_id,title,body,type,reference_id)
  values(r.delivery_guy_id,'Delivery rejected',
         'Your delivery request was rejected.' || case when coalesce(rejection_reason,'')<>'' then ' Reason: '||rejection_reason else '' end,
         'delivery',r.id);
  return r;
end;
$$;

create or replace function public.complete_delivery_request(request_id uuid)
returns public.delivery_requests
language plpgsql security definer set search_path=public
as $$
declare r public.delivery_requests;
declare p public.products;
begin
  if not public.is_admin() then raise exception 'Admin access required'; end if;
  select * into r from public.delivery_requests where id=request_id for update;
  if r.id is null then raise exception 'Delivery request not found'; end if;
  if r.status <> 'delivery_note_submitted' then raise exception 'Delivery note must be submitted first'; end if;

  update public.inventory_units set status='delivered', updated_at=now()
  where id=r.unit_id and status in ('reserved','out_for_delivery');
  if not found then raise exception 'Inventory unit is not reserved'; end if;

  update public.products set quantity=greatest(0,quantity-1), updated_at=now()
  where id=r.product_id returning * into p;

  update public.delivery_requests
  set status='completed', completed_at=now(), completed_by=auth.uid()
  where id=request_id returning * into r;

  insert into public.notifications(recipient_id,title,body,type,reference_id)
  values(r.delivery_guy_id,'Delivery completed',
         'Delivery for serial ' || (select serial_number from public.inventory_units where id=r.unit_id) || ' was completed successfully.',
         'delivery',r.id);
  return r;
end;
$$;

grant execute on function public.approve_delivery_request(uuid) to authenticated;
grant execute on function public.reject_delivery_request(uuid,text) to authenticated;
grant execute on function public.complete_delivery_request(uuid) to authenticated;

-- Trigger: new request -> notify every admin.
create or replace function public.notify_new_delivery()
returns trigger language plpgsql security definer set search_path=public as $$
declare a record;
begin
  for a in select user_id from public.admin_users loop
    insert into public.notifications(recipient_id,title,body,type,reference_id)
    values(a.user_id,'New delivery request',
      'A delivery request for serial ' || (select serial_number from public.inventory_units where id=new.unit_id) ||
      ' was submitted for ' || new.destination || '.','delivery',new.id);
  end loop;
  return new;
end;
$$;

drop trigger if exists delivery_request_notify on public.delivery_requests;
create trigger delivery_request_notify after insert on public.delivery_requests
for each row execute function public.notify_new_delivery();

create or replace function public.notify_delivery_note()
returns trigger language plpgsql security definer set search_path=public as $$
declare a record;
begin
  if new.status='delivery_note_submitted' and old.status is distinct from new.status then
    for a in select user_id from public.admin_users loop
      insert into public.notifications(recipient_id,title,body,type,reference_id)
      values(a.user_id,'Delivery note submitted',
        'A delivery note is ready for review for serial ' || (select serial_number from public.inventory_units where id=new.unit_id) || '.',
        'delivery',new.id);
    end loop;
  end if;
  return new;
end;
$$;

drop trigger if exists delivery_note_notify on public.delivery_requests;
create trigger delivery_note_notify after update on public.delivery_requests
for each row execute function public.notify_delivery_note();

